/**
 * Image-8 / I8-2A — F6b: the PACKED publish entry really reaches the codec.
 *
 * I8-1 shipped the codec behind a consumer-less module and the bundle
 * tree-shook it away: `dist/index.mjs` contained ZERO `sixelEncode`
 * occurrences. F6a proved the packed dependency and the worker/CJS encode in
 * isolation, and the Owner deferred F6b to the first real production consumer
 * with mandatory re-entry here. This file is that re-entry.
 *
 * Contract:
 *
 * - the artifact under test is the tarball `pnpm pack` produced for this commit
 *   (never a source-tree import and never a test-only entry point);
 * - the child process runs the INSTALLED package's own `exports` entry, builds
 *   the production `TuiApp`, feeds the real DA1 / `CSI 6;h;w t` / OSC 11 replies,
 *   types the draft placeholder into the real editor, and reports the exact DCS
 *   the app's Screen wrote;
 * - the parent decodes those bytes with the independent oracle.
 *
 * A missing tarball SKIPS (a product-lane run happens before `pnpm pack` exists).
 * `SIXEL_PACKAGED_PATH_REQUIRED=1` turns that skip into a hard failure, which is
 * how the stage's evidence run is executed.
 * @module @xmoon76/dsh-pi-tui/integration/sixel-packaged-path.test
 */

import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import test from 'node:test'
import { decodeSixel, pixelAt } from '../support/sixel-oracle.ts'
import { testLifecycle } from '../support/temp-lifecycle.ts'

const PACKAGE_ROOT = resolve(import.meta.dirname, '..', '..')

/** The newest `xmoon76-dsh-pi-tui-*.tgz` in the repository root, if any. */
function packedTarball(): string | undefined {
  const explicit = process.env.SIXEL_PACKED_TARBALL
  if (explicit !== undefined && explicit !== '') return existsSync(explicit) ? explicit : undefined
  const candidates = readdirSync(PACKAGE_ROOT)
    .filter(name => /^xmoon76-dsh-pi-tui-.*\.tgz$/u.test(name))
    .map(name => join(PACKAGE_ROOT, name))
    .sort()
  return candidates.at(-1)
}

/**
 * The child program: the packed package's own entry, driven as the product
 * drives it. It prints one JSON line with the DCS the Screen wrote.
 */
const CHILD_SCRIPT = `
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)

const packed = require.resolve('@xmoon76/dsh-pi-tui')
const { pathToFileURL } = await import('node:url')
const entry = await import(pathToFileURL(packed).href)
const { TuiApp } = entry
if (typeof TuiApp !== 'function') {
  console.log(JSON.stringify({ ok: false, reason: 'the packed entry does not export TuiApp' }))
  process.exit(0)
}

const listeners = new Set()
const writes = []
const terminal = {
  columns: 100,
  rows: 24,
  kittyProtocolActive: false,
  start(onInput) { this.onInput = onInput },
  stop() {},
  async drainInput() {},
  write(data) { writes.push(data) },
  moveBy() {},
  hideCursor() {},
  showCursor() {},
  clearLine() {},
  clearFromCursor() {},
  clearScreen() {},
  setTitle() {},
  setProgress() {},
  setProgramStatus() {},
  setProgressState() {},
  onSixelSupport(listener) { listeners.add(listener); return () => listeners.delete(listener) },
}

// A real two-band PNG (80x40: red over blue), generated by the codec stage's own
// sharp — the same dependency the packaged codec uses.
const { default: sharp } = await import('sharp')
const rgba = new Uint8Array(80 * 40 * 4)
for (let y = 0; y < 40; y += 1) {
  for (let x = 0; x < 80; x += 1) {
    const offset = (y * 80 + x) * 4
    const top = y < 20
    rgba[offset] = top ? 255 : 0
    rgba[offset + 1] = 0
    rgba[offset + 2] = top ? 0 : 255
    rgba[offset + 3] = 255
  }
}
const png = new Uint8Array(await sharp(Buffer.from(rgba), { raw: { width: 80, height: 40, channels: 4 } }).png().toBuffer())

const image = {
  id: 1,
  kind: 'image',
  source: { type: 'draft' },
  bytes: png,
  mediaType: 'image/png',
  width: 80,
  height: 40,
  byteLength: png.byteLength,
  name: 'bands.png',
  placeholder: '[image #1 (80×40)]',
}
const store = { values: () => [image] }
const app = new TuiApp(terminal, { onSubmit() {}, onExit() {}, onCancel() {} }, { draftImagePreviewSource: store })
app.start()

for (const listener of [...listeners]) listener(true)
await waitFor(() => writes.join('').includes('\\u001b[16t'), 'the geometry query')
terminal.onInput('\\u001b[6;40;20t')
await waitFor(() => writes.join('').includes('\\u001b]11;?'), 'the background query')
terminal.onInput('\\u001b]11;rgb:2828/2c2c/3434\\u0007')
await sleep(50)
writes.length = 0
terminal.onInput(image.placeholder)
await waitFor(() => writes.join('').includes('\\u001bP'), 'the encoded raster', 20000)

const wire = writes.join('')
const start = wire.lastIndexOf('\\u001bP')
const end = wire.indexOf('\\u001b\\\\', start)
console.log(JSON.stringify({ ok: true, entry: packed, dcs: wire.slice(start, end + 2), kitty: wire.includes('\\u001b_G') }))
app.dispose?.()

async function sleep(ms) { await new Promise(resolve => setTimeout(resolve, ms)) }
async function waitFor(predicate, label, timeoutMs = 20000) {
  const deadline = Date.now() + timeoutMs
  while (!predicate()) {
    if (Date.now() > deadline) {
      console.log(JSON.stringify({ ok: false, reason: 'timed out waiting for ' + label }))
      process.exit(0)
    }
    await sleep(10)
  }
}
`

test('the PACKED publish entry paints a draft card through the real SIXEL chain (F6b)', async (t) => {
  const tarball = packedTarball()
  if (tarball === undefined) {
    if (process.env.SIXEL_PACKAGED_PATH_REQUIRED === '1') {
      assert.fail('SIXEL_PACKAGED_PATH_REQUIRED=1 but no xmoon76-dsh-pi-tui-*.tgz exists; run `pnpm pack` first')
    }
    t.skip('no packed tarball in the repository root (run `pnpm pack` to exercise F6b)')
    return
  }

  const root = testLifecycle(t).tempDir('sixel-packed-')
  // Install the artifact as a consumer would. `--prefer-offline` keeps the run
  // reproducible without a network round trip when the cache is warm.
  const install = spawnSync(
    'npm',
    ['install', '--omit=dev', '--no-audit', '--no-fund', '--prefer-offline', '--loglevel=error', tarball],
    { cwd: root, encoding: 'utf8', timeout: 600_000 },
  )
  assert.equal(install.status, 0, `the tarball must install standalone:\n${install.stdout}\n${install.stderr}`)

  const script = join(root, 'f6b.mjs')
  writeFileSync(script, CHILD_SCRIPT)
  const child = spawnSync(process.execPath, [script], {
    cwd: root,
    encoding: 'utf8',
    timeout: 300_000,
    env: { ...process.env, DSH_HOME: join(root, 'home') },
  })
  assert.equal(child.status, 0, `the packed consumer must run:\n${child.stdout}\n${child.stderr}`)
  const line = child.stdout.trim().split('\n').filter(entry => entry.startsWith('{')).at(-1)
  assert.ok(line !== undefined, `the child must report one JSON result, got:\n${child.stdout}`)
  const result = JSON.parse(line) as { ok: boolean; reason?: string; entry?: string; dcs?: string; kitty?: boolean }
  assert.equal(result.ok, true, `the packed consumer failed: ${result.reason ?? 'unknown'}`)
  assert.ok(result.entry!.includes('node_modules'), `the code under test is the INSTALLED entry: ${result.entry}`)
  assert.equal(result.kitty, false, 'no Kitty APC is emitted')

  const decoded = decodeSixel(result.dcs!)
  assert.equal(decoded.width, 80, 'the real source width reached the encoder')
  assert.ok(decoded.height > 0 && decoded.height % 6 === 0, 'a whole number of SIXEL bands')
  const [topR, , topB] = pixelAt(decoded, 4, 4)
  assert.ok(topR > 180 && topB < 80, `the top band is red, got ${topR},${topB}`)
  const [, , bottomBlue] = pixelAt(decoded, 4, decoded.height - 8)
  assert.ok(bottomBlue > 180, 'the bottom band is blue')
})
